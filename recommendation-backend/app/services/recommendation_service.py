def _load_model_metrics() -> dict[str, Any]:
    """Measured performance of the model that actually produces findings.

    This used to report metrics for recommendation_model.joblib, which was
    trained on labels generated by the same heuristic it replaced and was
    never loaded at runtime. It now reports the editorial-problem classifier,
    read from the trained bundle itself so the numbers cannot drift away from
    the model in use.
    """
    from app.services.problem_model import PROBLEM_CLASSES, load_model

    bundle = load_model()
    if bundle is None:
        return {
            "model": "editorial-problem-classifier",
            "status": "not trained — run scripts/train_problem_model.py",
        }
    return {
        "model": "editorial-problem-classifier (RandomForest)",
        "cv_accuracy": bundle.get("cv_accuracy"),
        "cv_strategy": bundle.get("cv_strategy", "legacy window-level split"),
        "trained_on_trailers": bundle.get("trained_on"),
        "training_examples": bundle.get("n_examples"),
        "problem_classes": list(PROBLEM_CLASSES),
        "training_data_source": (
            "professional trailers with deliberate, named editorial defects applied "
            "— labels come from the applied defect, not from a heuristic's own output"
        ),
    }




def _number(value: Any, default: float = 0.0) -> float:
    try:
        number = float(value)
        return number if np.isfinite(number) else default
    except (TypeError, ValueError):
        return default


def _score(value: Any) -> float:
    number = _number(value)
    return max(0.0, min(1.0, number / 100 if number > 1 else number))


def _text(value: Any, default: str = "unknown") -> str:
    if value is None:
        return default
    text = str(value).strip()
    return text or default


def _pick(row: dict[str, Any], *keys: str, default: Any = None) -> Any:
    for key in keys:
        if key in row and row[key] is not None:
            return row[key]
    return default


def _parse_shot_duration(timeframe: str) -> float:
    try:
        start_text, end_text = timeframe.split("-")
        def _to_seconds(text: str) -> float:
            parts = [float(p) for p in text.strip().split(":")]
            sec = 0.0
            for p in parts:
                sec = sec * 60 + p
            return sec
        return max(1.0, _to_seconds(end_text) - _to_seconds(start_text))
    except Exception:
        return 8.0


def _build_scene_rows(payload: RecommendationRequest) -> list[dict[str, Any]]:
    """Builds clean, normalized scene feature rows from multimodal backend outputs.

    Enhanced to include scene_type_confidence and classification_reliable fields.
    """
    final_rows = payload.final_system_output or []
    audio_rows = payload.audio_feature_output or []
    visual_rows = payload.visual_feature_output or []
    scene_count = max(len(final_rows), len(audio_rows), len(visual_rows))
    rows: list[dict[str, Any]] = []

    total_duration = 0.0
    for idx in range(scene_count):
        final = final_rows[idx] if idx < len(final_rows) else {}
        timeframe = _text(_pick(final, "time", "timestamp", default=f"00:{idx*8:02d}-00:{(idx+1)*8:02d}"))
        total_duration += _parse_shot_duration(timeframe)

    trailer_type = detect_trailer_type(total_duration, scene_count)

    for index in range(scene_count):
        final = final_rows[index] if index < len(final_rows) else {}
        audio = audio_rows[index] if index < len(audio_rows) else {}
        visual = visual_rows[index] if index < len(visual_rows) else {}

        scene = int(_number(_pick(final, "scene", "scene_id", default=index + 1), index + 1))
        timeframe = _text(_pick(final, "time", "timestamp", default=_pick(visual, "time", "timestamp", default=f"00:{index*8:02d}-00:{(index+1)*8:02d}")))
        position_ratio = (index + 0.5) / max(scene_count, 1)

        act = get_act_phase(position_ratio, trailer_type)

        face_emo = _text(_pick(final, "face_emotion", "visual_emotion", "emotion", default=_pick(visual, "face_emotion", "visual_emotion", "emotion", default="neutral")))
        if face_emo in ["left", "right"]:
            face_emo = _text(_pick(final, "video_emotion", "visual_emotion", default="neutral"))
            if face_emo in ["left", "right"]:
                face_emo = "neutral"

        # Extract scene_type_confidence and classification_reliable
        scene_type_conf = _number(
            _pick(final, "scene_type_confidence", "fusion_confidence",
                  default=_pick(visual, "scene_type_confidence", default=1.0)),
            1.0
        )
        classification_reliable_raw = _pick(
            final, "classification_reliable",
            default=_pick(visual, "classification_reliable", default=True)
        )
        classification_reliable = bool(classification_reliable_raw) if classification_reliable_raw is not None else True

        evidence = Evidence(
            ei=_score(_pick(final, "ei", "EI", "emotional_intensity", "intensity_score")),
            audio_energy=_score(_pick(final, "audio_energy", "A", "audioEnergy", default=_pick(audio, "audioEnergy", "audio_energy", "A"))),
            motion=_score(_pick(final, "motion", "M", "motion_intensity", default=_pick(visual, "motion", "motion_intensity", "M"))),
            object_score=_score(_pick(final, "object_score", "O", "objectScore", default=_pick(visual, "objectScore", "object_score", "O"))),
            emotion_confidence=_score(_pick(final, "emotion_confidence", "F", default=_pick(visual, "emotionConfidence", "emotion_confidence", "F", default=0.85))),
            scene_type=_text(_pick(final, "scene_type", "sceneType", default=_pick(visual, "scene_type", "sceneType", default="Drama"))),
            scene_type_confidence=scene_type_conf,
            classification_reliable=classification_reliable,
            visual_emotion=face_emo,
            audio_mood=_text(_pick(final, "audio_mood", "mood", default=_pick(audio, "audioMood", "audio_mood", "mood", default="emotional"))),
            act=act,
            audio_emotion=_text(_pick(final, "audio_emotion", default=_pick(audio, "audio_emotion", default="neutral"))),
            tempo_bpm=_number(_pick(final, "tempo_bpm", default=_pick(audio, "tempo_bpm", default=120.0)), 120.0),
            mfcc_mean=_number(_pick(final, "mfcc_mean", default=_pick(audio, "mfcc_mean", default=0.0)), 0.0),
            spectral_centroid=_number(_pick(final, "spectral_centroid", default=_pick(audio, "spectral_centroid", default=1800.0)), 1800.0),
            shot_duration=_parse_shot_duration(timeframe),
            objects=_text(_pick(final, "objects", default=_pick(visual, "objects", default="person")), "person"),
        )

        rows.append({
            "scene": scene,
            "timeframe": timeframe,
            "evidence": evidence,
            "act": act,
            "position_pct": position_ratio
        })

    return rows


def _refine_scene_types(scene_rows: list[dict[str, Any]]) -> dict[str, int]:
    """Correct only isolated, low-confidence scene labels.

    Trailer cuts legitimately change scene type quickly, so broad temporal
    smoothing would erase real transitions. A label is changed only when both
    immediate neighbours are reliable, agree, and the current prediction is
    uncertain. Unresolved very-low-confidence labels are marked unreliable so
    later genre and intent logic cannot treat them as facts.
    """
    if not scene_rows:
        return {"corrected": 0, "unreliable": 0}

    original = [row["evidence"].scene_type for row in scene_rows]
    confidences = [
        max(0.0, min(1.0, float(row["evidence"].scene_type_confidence or 0.0)))
        for row in scene_rows
    ]
    reliable = [
        bool(row["evidence"].classification_reliable) and confidence >= 0.45
        for row, confidence in zip(scene_rows, confidences)
    ]

    corrected = 0
    for index in range(1, len(scene_rows) - 1):
        evidence = scene_rows[index]["evidence"]
        if confidences[index] >= 0.55 and reliable[index]:
            continue

        neighbour_type = original[index - 1]
        neighbours_agree = (
            reliable[index - 1]
            and reliable[index + 1]
            and neighbour_type == original[index + 1]
            and neighbour_type != original[index]
        )
        if not neighbours_agree:
            continue

        evidence.scene_type = neighbour_type
        evidence.scene_type_confidence = round(
            min(0.78, (confidences[index - 1] + confidences[index + 1]) * 0.425),
            4,
        )
        evidence.classification_reliable = True
        scene_rows[index]["scene_type_refinement"] = {
            "original": original[index],
            "refined": neighbour_type,
            "reason": "matching reliable adjacent scenes",
        }
        corrected += 1

    unreliable = 0
    for row in scene_rows:
        evidence = row["evidence"]
        evidence.scene_type_confidence = max(
            0.0, min(1.0, float(evidence.scene_type_confidence or 0.0))
        )
        if evidence.scene_type_confidence < 0.35:
            evidence.classification_reliable = False
            unreliable += 1

    return {"corrected": corrected, "unreliable": unreliable}


